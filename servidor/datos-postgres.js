const { Pool } = require("pg");
const { urlBaseDatos } = require("./configuracion");
const conexion = new URL(urlBaseDatos);
if (process.env.NODE_ENV === "production" || conexion.hostname.endsWith(".neon.tech")) {
    conexion.searchParams.set("sslmode", "verify-full");
}
const pool = new Pool({ connectionString: conexion.toString(), max: 5,
    connectionTimeoutMillis: 15000, idleTimeoutMillis: 10000, allowExitOnIdle: true,
    enableChannelBinding: true });
pool.on("error", () => console.error("Se perdió una conexión con la base de datos"));
function errorBaseDatos(causa) {
    const error = new Error("No se pudo acceder a la base de datos");
    error.estado = 503;
    const codigos = new Set(["28P01", "28000", "3D000", "42501", "ENOTFOUND", "ETIMEDOUT", "ECONNREFUSED", "ECONNRESET", "ERR_TLS_CERT_ALTNAME_INVALID", "UNABLE_TO_VERIFY_LEAF_SIGNATURE", "SELF_SIGNED_CERT_IN_CHAIN", "CERT_HAS_EXPIRED"]);
    error.codigo = codigos.has(causa?.code) ? causa.code : "CONEXION_NO_DISPONIBLE";
    return error;
}
let inicializacion;
async function inicializar() {
    if (!inicializacion) {
        inicializacion = pool.query(`CREATE TABLE IF NOT EXISTS usuarios (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email TEXT NOT NULL UNIQUE,
            clave TEXT NOT NULL,
            activo BOOLEAN NOT NULL DEFAULT TRUE,
            rol TEXT NOT NULL DEFAULT 'usuario' CHECK(rol IN ('usuario', 'administrador'))
        )`).catch(error => { inicializacion = undefined; throw errorBaseDatos(error); });
    }
    await inicializacion;
}
async function consultar(sql, parametros = []) {
    await inicializar();
    try { return await pool.query(sql, parametros); }
    catch (error) {
        if (error.code === "23505") throw new Error("Ya existe un usuario con ese email");
        throw errorBaseDatos(error);
    }
}
async function buscarPorEmail(email) { return (await consultar("SELECT * FROM usuarios WHERE email = $1", [email])).rows[0]; }
async function buscarPorId(id) {
    if (!Number.isSafeInteger(Number(id))) return undefined;
    return (await consultar("SELECT * FROM usuarios WHERE id = $1", [Number(id)])).rows[0];
}
async function listar() { return (await consultar("SELECT * FROM usuarios ORDER BY id")).rows; }
async function crear(email, claveHash) {
    return (await consultar("INSERT INTO usuarios (email, clave) VALUES ($1, $2) RETURNING *", [email, claveHash])).rows[0];
}
async function desactivar(id) {
    if (!await buscarPorId(id)) throw new Error("Usuario no encontrado");
    return (await consultar("UPDATE usuarios SET activo = FALSE WHERE id = $1 RETURNING *", [Number(id)])).rows[0];
}
async function promoverAdministrador(id) {
    if (!(await buscarPorId(id))?.activo) throw new Error("Usuario no encontrado o eliminado");
    return (await consultar("UPDATE usuarios SET rol = 'administrador' WHERE id = $1 RETURNING *", [Number(id)])).rows[0];
}
async function limpiar() { throw new Error("No se permite limpiar la base de datos PostgreSQL"); }
async function cerrar() { await pool.end(); }
module.exports = { buscarPorEmail, buscarPorId, listar, crear, desactivar, limpiar, promoverAdministrador, inicializar, cerrar };
